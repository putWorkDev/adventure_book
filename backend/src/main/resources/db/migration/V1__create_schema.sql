-- =====================================================================
-- Adventure Book schema
--
-- Books are always stored, even when invalid (see ValidationErrorCode).
-- Because of that, section numbers are NOT unique per book and option
-- targets (goto_section_number) are NOT foreign keys: a book with a
-- duplicate section id or a dangling gotoId must still be persistable so
-- its validation report can be shown. Only valid books can be played.
--
-- Enum-like columns are VARCHAR + CHECK (IN ...) and mirror the Java enums
-- persisted with @Enumerated(EnumType.STRING).
-- Position uniqueness is deferred to transaction commit because replacing a
-- collection may INSERT new rows before Hibernate DELETEs the old ones.
-- =====================================================================

CREATE TABLE book (
    id              VARCHAR(100)                NOT NULL,
    title           VARCHAR(255)                NOT NULL,
    -- author / difficulty are nullable only for UNPARSEABLE books (e.g. empty file)
    author          VARCHAR(255),
    difficulty      VARCHAR(10),
    source          VARCHAR(10)                 NOT NULL,
    -- original JSON as received; kept for re-validation and for data that
    -- cannot be represented in the normalised tables (unparseable / invalid values)
    source_json     TEXT,
    -- denormalised for cheap listing / filtering / sorting
    section_count   INT             DEFAULT 0   NOT NULL,
    ending_count    INT             DEFAULT 0   NOT NULL,
    valid           BOOLEAN         DEFAULT FALSE NOT NULL,
    error_count     INT             DEFAULT 0   NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version         BIGINT          DEFAULT 0   NOT NULL,
    CONSTRAINT pk_book PRIMARY KEY (id),
    CONSTRAINT ck_book_id_slug CHECK (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_book_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD')),
    CONSTRAINT ck_book_source CHECK (source IN ('FILE', 'UPLOAD')),
    CONSTRAINT ck_book_counts CHECK (section_count >= 0 AND ending_count >= 0 AND error_count >= 0),
    CONSTRAINT ck_book_valid_consistency CHECK (valid = (error_count = 0))
);

CREATE INDEX ix_book_title ON book (title);
-- author filter is a case-insensitive exact match: lower(author) = ?
CREATE INDEX ix_book_author_lower ON book (lower(author));
CREATE INDEX ix_book_difficulty ON book (difficulty);

CREATE TABLE book_section (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    book_id         VARCHAR(100)    NOT NULL,
    -- the "id" of the section inside the book JSON (e.g. 1, 20, 500)
    section_number  INT             NOT NULL,
    -- order of the section in the source file
    position        INT             NOT NULL,
    type            VARCHAR(10)     NOT NULL,
    text            TEXT            NOT NULL,
    CONSTRAINT pk_book_section PRIMARY KEY (id),
    CONSTRAINT fk_book_section_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT uq_book_section_position UNIQUE (book_id, position) DEFERRABLE INITIALLY DEFERRED,
    -- target of game's composite FK: guarantees a game's section belongs to the game's book
    CONSTRAINT uq_book_section_id_book UNIQUE (id, book_id),
    CONSTRAINT ck_book_section_type CHECK (type IN ('BEGIN', 'NODE', 'END')),
    CONSTRAINT ck_book_section_position CHECK (position >= 0)
);

CREATE INDEX ix_book_section_number ON book_section (book_id, section_number);
CREATE INDEX ix_book_section_type ON book_section (book_id, type);

CREATE TABLE section_option (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    section_id          BIGINT          NOT NULL,
    -- index of the option within its section; exposed by the API as optionId
    position            INT             NOT NULL,
    description         VARCHAR(1000)   NOT NULL,
    goto_section_number INT             NOT NULL,
    -- optional consequence (all null, or type + value set)
    consequence_type    VARCHAR(20),
    consequence_value   INT,
    consequence_text    VARCHAR(1000),
    CONSTRAINT pk_section_option PRIMARY KEY (id),
    CONSTRAINT fk_section_option_section FOREIGN KEY (section_id) REFERENCES book_section (id) ON DELETE CASCADE,
    CONSTRAINT uq_section_option_position UNIQUE (section_id, position) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_section_option_position CHECK (position >= 0),
    CONSTRAINT ck_section_option_consequence_type CHECK (consequence_type IN ('LOSE_HEALTH', 'GAIN_HEALTH')),
    CONSTRAINT ck_section_option_consequence CHECK ((
        (consequence_type IS NULL AND consequence_value IS NULL AND consequence_text IS NULL)
        OR (consequence_type IS NOT NULL AND consequence_value IS NOT NULL AND consequence_value > 0)
    ) IS TRUE)
);

CREATE TABLE book_validation_error (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    book_id             VARCHAR(100)    NOT NULL,
    position            INT             NOT NULL,
    code                VARCHAR(30)     NOT NULL,
    message             VARCHAR(1000)   NOT NULL,
    section_number      INT,
    option_index        INT,
    goto_section_number INT,
    CONSTRAINT pk_book_validation_error PRIMARY KEY (id),
    CONSTRAINT fk_book_validation_error_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT uq_book_validation_error_position UNIQUE (book_id, position) DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT ck_book_validation_error_position CHECK (position >= 0 AND (option_index IS NULL OR option_index >= 0)),
    CONSTRAINT ck_book_validation_error_code CHECK (code IN (
        'NO_BEGINNING', 'MULTIPLE_BEGINNINGS', 'NO_ENDING', 'INVALID_GOTO',
        'NODE_WITHOUT_OPTIONS', 'DUPLICATE_SECTION_ID', 'INVALID_CONSEQUENCE', 'UNPARSEABLE'))
);

CREATE TABLE game (
    id                  UUID            NOT NULL,
    book_id             VARCHAR(100)    NOT NULL,
    current_section_id  BIGINT          NOT NULL,
    status              VARCHAR(20)     NOT NULL,
    health              INT             NOT NULL,
    max_health          INT DEFAULT 10  NOT NULL,
    step_count          INT DEFAULT 0   NOT NULL,
    -- consequence applied by the most recent choice (all null when none)
    last_consequence_type           VARCHAR(20),
    last_consequence_value          INT,
    last_consequence_text           VARCHAR(1000),
    last_consequence_health_before  INT,
    last_consequence_health_after   INT,
    started_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    saved_at            TIMESTAMP(6) WITH TIME ZONE,
    finished_at         TIMESTAMP(6) WITH TIME ZONE,
    version             BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT pk_game PRIMARY KEY (id),
    CONSTRAINT fk_game_book FOREIGN KEY (book_id) REFERENCES book (id) ON DELETE CASCADE,
    CONSTRAINT fk_game_current_section FOREIGN KEY (current_section_id, book_id)
        REFERENCES book_section (id, book_id) ON DELETE CASCADE,
    CONSTRAINT ck_game_status CHECK (status IN ('IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DIED', 'ABANDONED')),
    CONSTRAINT ck_game_health CHECK (max_health > 0 AND health >= 0 AND health <= max_health),
    CONSTRAINT ck_game_step_count CHECK (step_count >= 0),
    -- a game is DIED exactly when health is 0
    CONSTRAINT ck_game_died CHECK ((status = 'DIED') = (health = 0)),
    -- finished_at is set only for terminal statuses
    CONSTRAINT ck_game_finished CHECK (
        (status IN ('COMPLETED', 'DIED', 'ABANDONED')) = (finished_at IS NOT NULL)
    ),
    CONSTRAINT ck_game_last_consequence_type CHECK (last_consequence_type IN ('LOSE_HEALTH', 'GAIN_HEALTH')),
    -- last consequence is either absent or fully described (text is optional)
    CONSTRAINT ck_game_last_consequence CHECK ((
        (last_consequence_type IS NULL AND last_consequence_value IS NULL AND last_consequence_text IS NULL
            AND last_consequence_health_before IS NULL AND last_consequence_health_after IS NULL)
        OR (last_consequence_type IS NOT NULL AND last_consequence_value > 0
            AND last_consequence_health_before IS NOT NULL AND last_consequence_health_after = health)
    ) IS TRUE)
);

CREATE INDEX ix_game_book ON game (book_id);
-- supports the FK (section deletes / cascades) and "games currently at section X"
CREATE INDEX ix_game_current_section ON game (current_section_id);
CREATE INDEX ix_game_status ON game (status);
CREATE INDEX ix_game_updated_at ON game (updated_at DESC);

CREATE TABLE game_step (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    game_id                 UUID            NOT NULL,
    step                    INT             NOT NULL,
    from_section_number     INT             NOT NULL,
    option_index            INT             NOT NULL,
    -- snapshot, so history stays readable even if the book changes
    option_description      VARCHAR(1000)   NOT NULL,
    to_section_number       INT             NOT NULL,
    consequence_type            VARCHAR(20),
    consequence_value           INT,
    consequence_text            VARCHAR(1000),
    consequence_health_before   INT,
    consequence_health_after    INT,
    health_after            INT             NOT NULL,
    created_at              TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT pk_game_step PRIMARY KEY (id),
    CONSTRAINT fk_game_step_game FOREIGN KEY (game_id) REFERENCES game (id) ON DELETE CASCADE,
    CONSTRAINT uq_game_step UNIQUE (game_id, step),
    CONSTRAINT ck_game_step_step CHECK (step >= 1),
    CONSTRAINT ck_game_step_option_index CHECK (option_index >= 0),
    CONSTRAINT ck_game_step_health CHECK (health_after >= 0),
    CONSTRAINT ck_game_step_consequence_type CHECK (consequence_type IN ('LOSE_HEALTH', 'GAIN_HEALTH')),
    CONSTRAINT ck_game_step_consequence CHECK ((
        (consequence_type IS NULL AND consequence_value IS NULL AND consequence_text IS NULL
            AND consequence_health_before IS NULL AND consequence_health_after IS NULL)
        OR (consequence_type IS NOT NULL AND consequence_value > 0
            AND consequence_health_before IS NOT NULL AND consequence_health_after = health_after)
    ) IS TRUE)
);
